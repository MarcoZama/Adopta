/** Texts that the flows complete with technical details: only the fixed start is translated. */
const FLOW_PREFIXES_EN: [string, string][] = [
  [
    "Pianificazione non confermata. Controlla lo stato prima di riprovare. ",
    "Scheduling not confirmed. Check the status before trying again. ",
  ],
  [
    "Agente non installato in Teams per questo destinatario: la card non e stata consegnata. Risposta di Teams: ",
    "Agent not installed in Teams for this recipient: the card was not delivered. Teams response: ",
  ],
];

export function translateFlowText(text: string, language: keyof typeof MESSAGES): string {
  if (language === "it" || !text) return text;
  const exact = FLOW_TEXTS_EN[text.trim()];
  if (exact) return exact;
  const prefix = FLOW_PREFIXES_EN.find(([source]) => text.startsWith(source));
  return prefix ? prefix[1] + text.slice(prefix[0].length) : text;
}
